//! `THIRD_PARTY_LICENSES`: what Help › Third-Party Notices shows and the
//! bundle ships. A header, the components cargo cannot see
//! (`licenses/bundled.txt`), the crates in Velopack's native binaries
//! (`licenses/velopack.txt`, from scripts/release/velopack-notices.sh), then
//! every crate PwrDisk compiles in, from cargo-about, as `PwrRoute` writes its
//! own; `--check` is the gate that it is current.

use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

pub fn licenses(check: bool) -> Result<(), String> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .ok_or("xtask has no parent directory")?
        .to_path_buf();
    let target = root.join("target");
    fs::create_dir_all(&target).map_err(|err| err.to_string())?;
    // Written to a file, not read from stdout: under PowerShell,
    // cargo-about refuses to write to a pipe.
    let generated = target.join("cargo-about.txt");
    let out = Command::new("cargo")
        .args([
            "about",
            "generate",
            "-c",
            "licenses/about.toml",
            "licenses/about.hbs",
            "--workspace",
            // --locked, not --frozen: a fresh runner has not downloaded the
            // other targets' crates, whose license files this reads.
            "--locked",
            "--fail",
            "-o",
        ])
        .arg(&generated)
        .current_dir(&root)
        .output()
        .map_err(|err| {
            format!(
                "cargo-about is required \
                 (`cargo install --locked cargo-about`): {err}"
            )
        })?;
    if !out.status.success() {
        return Err(format!(
            "cargo about generate failed:\n{}",
            String::from_utf8_lossy(&out.stderr)
        ));
    }
    let crates = read(&generated)?;
    let bundled = read(&root.join("licenses/bundled.txt"))?;
    let velopack = read(&root.join("licenses/velopack.txt"))?;
    let notice = normalize(&format!(
        "PwrDisk Third-Party Licenses\n\
         ============================\n\
         \n\
         Generated by `cargo xtask licenses` from Cargo.lock (cargo-about),\n\
         licenses/bundled.txt and licenses/velopack.txt. Do not edit this\n\
         file by hand.\n\
         \n\
         PwrDisk's own license, which carries disktree's, is in LICENSE.\n\
         \n\
         {bundled}\n{velopack}\n{crates}"
    ));
    let path = root.join("THIRD_PARTY_LICENSES");
    if check {
        let current = normalize(&read(&path)?);
        if current != notice {
            let fresh = target.join("THIRD_PARTY_LICENSES.generated");
            fs::write(&fresh, &notice).map_err(|err| err.to_string())?;
            return Err(format!(
                "THIRD_PARTY_LICENSES is out of date: run `cargo xtask \
                 licenses` and commit it (fresh copy: {})",
                fresh.display()
            ));
        }
        println!("THIRD_PARTY_LICENSES is current");
    } else {
        fs::write(&path, notice).map_err(|err| err.to_string())?;
        println!("wrote {}", path.display());
    }
    Ok(())
}

fn read(path: &PathBuf) -> Result<String, String> {
    fs::read_to_string(path)
        .map_err(|err| format!("could not read {}: {err}", path.display()))
}

/// LF line endings and exactly one trailing newline: some crates ship CRLF
/// license files.
fn normalize(text: &str) -> String {
    text.replace("\r\n", "\n").trim_end().to_owned() + "\n"
}
